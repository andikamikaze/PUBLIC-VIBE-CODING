$ErrorActionPreference = "Stop"

# Script ini men-scan folder CLONE\ dan PROJECT\ lalu menulis projects-data.js.
# Jalankan ulang setiap kali ada file HTML yang ditambah/dihapus/diganti nama.
# Output selalu diambil dari nama file asli di disk supaya casing & spasi identik.

$root = Split-Path -Parent $MyInvocation.MyCommand.Path

function Get-HtmlNames([string]$folder) {
  $path = Join-Path $root $folder
  if (-not (Test-Path -LiteralPath $path)) {
    throw "Folder tidak ditemukan: $path"
  }
  return @(Get-ChildItem -LiteralPath $path -File -Filter "*.html" |
    Sort-Object -Property Name |
    ForEach-Object { $_.Name })
}

# Escaping literals untuk source code JavaScript.
function Escape-Js([string]$value) {
  return $value.Replace('\', '\\').Replace('"', '\"')
}

function Format-JsArray([string]$name, [string[]]$files) {
  $lines = @("const $name = [")
  foreach ($file in $files) {
    $lines += '  "' + (Escape-Js $file) + '",'
  }
  $lines += "];"
  return ($lines -join "`r`n")
}

$clone = Get-HtmlNames "CLONE"
$project = Get-HtmlNames "PROJECT"
$total = $clone.Count + $project.Count

$content = @(
  "// Generated by generate-projects.ps1 - jangan diedit manual."
  "// CLONE: $($clone.Count) file | PROJECT: $($project.Count) file | Total: $total file"
  ""
  (Format-JsArray "CLONE_FILES" $clone)
  ""
  (Format-JsArray "PROJECT_FILES" $project)
  ""
) -join "`r`n"

$out = Join-Path $root "projects-data.js"
[System.IO.File]::WriteAllText($out, $content, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "CLONE: $($clone.Count) file"
Write-Host "PROJECT: $($project.Count) file"
Write-Host "Total: $total file"
Write-Host "Ditulis ke: $out"
